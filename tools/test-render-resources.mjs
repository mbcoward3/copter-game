import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import * as THREE from 'three';
const source=readFileSync(new URL('../src/render-resources.js',import.meta.url),'utf8');
const { sharedResource, retireObject, writeInstance, uploadInstances } = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const scene=new THREE.Scene(),root=new THREE.Group();scene.add(root);
const geometry=sharedResource(new THREE.BoxGeometry()), sharedMat=sharedResource(new THREE.MeshStandardMaterial()), privateMat=new THREE.MeshStandardMaterial(), depth=new THREE.MeshDepthMaterial();
const a=new THREE.Mesh(geometry,[sharedMat,privateMat]),b=new THREE.Mesh(geometry,privateMat);a.customDepthMaterial=depth;root.add(a,b);
const events={geometry:0,sharedMat:0,privateMat:0,depth:0};
for(const [key,r]of Object.entries({geometry,sharedMat,privateMat,depth}))r.addEventListener('dispose',()=>events[key]++);
retireObject(root);retireObject(root);
assert.deepEqual(events,{geometry:0,sharedMat:0,privateMat:1,depth:1},'Retirement preserves shared resources and releases private resources exactly once');
assert.equal(scene.children.length,0);
const batch=new THREE.InstancedMesh(geometry,sharedMat,100);batch.instanceMatrix.setUsage(THREE.DynamicDrawUsage);
const matrix=new THREE.Matrix4().makeTranslation(.1,3,5),color=new THREE.Color(.2,.4,.6);
writeInstance(batch,0,matrix,color);uploadInstances(batch,1);
assert.deepEqual(batch.instanceMatrix.updateRanges,[{start:0,count:16}]);
const version=batch.instanceMatrix.version;batch.instanceMatrix.clearUpdateRanges();
writeInstance(batch,0,matrix,color);uploadInstances(batch,1);
assert.equal(batch.instanceMatrix.version,version,'An unchanged transform does not upload again');
matrix.elements[12]=9;writeInstance(batch,0,matrix,color);uploadInstances(batch,1);
assert.ok(batch.instanceMatrix.version>version);
uploadInstances(batch,0);assert.equal(batch.visible,false);
console.log('Shared ownership, idempotent retirement and bounded instance upload regressions passed');
